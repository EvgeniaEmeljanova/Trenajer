const mk = (groups: [string, readonly string[], BlsCriterionKind?][]): BlsCriterion[] => {
  let number = 0;
  return groups.flatMap(([section, items, kind]) => items.map((text) => ({
    number: ++number, text, section, kind: kind ?? 'action'
  })));
};
const aed = (shock: boolean): string[] => [...common.aedCommon, ...(shock ? common.aedShock : []), ...common.aedRestart];
