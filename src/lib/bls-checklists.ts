export type BlsCriterionKind = 'action' | 'metric' | 'unsafe';

export type BlsCriterion = {
  number: number;
  text: string;
  kind: BlsCriterionKind;
  metric?: 'depth' | 'handPosition' | 'recoil' | 'rate' | 'ventilation';
  threshold?: number;
};

const action = (text: string): BlsCriterion => ({ number: 0, text, kind: 'action' });
const unsafe = (text: string): BlsCriterion => ({ number: 0, text, kind: 'unsafe' });
const metric = (text: string, metricId: NonNullable<BlsCriterion['metric']>): BlsCriterion => ({
  number: 0, text, kind: 'metric', metric: metricId, threshold: 80,
});

